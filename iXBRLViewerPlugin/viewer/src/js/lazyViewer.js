import $ from 'jquery'
import { Viewer } from './viewer.js';
import { IXNode } from './ixnode.js';
import { TableExport } from './tableExport.js';
import { runGenerator, viewerUniqueId } from './util.js';
import { OffscreenRendering } from './offscreenRendering.js';

const KIND_CLASSES = {
    f: "ixbrl-element-nonfraction",
    n: "ixbrl-element-nonnumeric",
    t: "ixbrl-element-footnote",
};

// Above this size, a cell's untagged padding is not checked for a fact that
// would use the whole cell as its wrapper.
const CELL_SCAN_LIMIT = 2000;
const OFFSCREEN_RESTART_DELAY = 500;
const OFFSCREEN_LOAD_POLL_INTERVAL = 250;

/*
 * An IXNode whose wrapper nodes are created on first use, from the element
 * located by its document index entry.
 */
class LazyIXNode extends IXNode {
    constructor(id, locator, docIndex, viewer) {
        super(id, undefined, docIndex);
        this.locator = locator;
        this._viewer = viewer;
    }

    get wrapperNodes() {
        return this._viewer.wrapLocator(this.locator) ?? $();
    }

    set wrapperNodes(nodes) {
        // Wrapper nodes are owned by the locator.
    }
}

/*
 * A Viewer that uses the document index generated by the plugin instead of
 * walking the document, and only inserts wrapper nodes for iXBRL elements
 * when they are needed for selection, hover or highlighting.  Elements are
 * wrapped in the same order as a full walk, so the resulting wrappers match
 * those that Viewer would create.
 *
 * Documents do not need to have finished loading, as events are delegated from
 * each document, and facts are located by ID as they are needed.
 */
export class LazyViewer extends Viewer {
    constructor(iv, iframes, reportSet) {
        super(iv, iframes, reportSet);
        // Per document, element ID to locator
        this._locators = [];
        this._bound = new WeakSet();
        this._tablesChecked = new WeakSet();
        this._cellsChecked = new WeakSet();
        this._newWrappers = [];
    }

    static documentIndexAvailable(reportSet) {
        const sourceReports = reportSet._data.sourceReports ?? [];
        return sourceReports.length > 0 && sourceReports.every(sr => sr.ixIndex !== undefined);
    }

    // Add viewer styles to any of the documents that don't have them yet.
    static applyStyles(iv, iframes) {
        const heads = iframes.contents().find("head").filter((i, head) => head.querySelector("style.ixv-viewer-style") === null);
        if (heads.length > 0) {
            const styleElts = $("<style>")
                .prop("type", "text/css")
                .addClass("ixv-viewer-style")
                .text(require('../less/viewer.less').toString())
                .appendTo(heads);
            iv.callPluginMethod("updateViewerStyleElements", styleElts);
        }
    }

    _applyStyles() {
        LazyViewer.applyStyles(this._iv, this._iframes);
    }

    initialize() {
        this._buildFromIndex();
        return this._checkContinuationCount().then(() => {
            this._reportSet.setIXNodeMap(this._ixNodeMap);
            this._applyStyles();
            this._bindHandlers();
            this.scale = 1;
            this._addDocumentSetTabs();
        });
    }

    _buildFromIndex() {
        const sourceReports = this._reportSet._data.sourceReports;
        const nextFileIndex = new Map();
        const docs = this._iframes.toArray().map((iframe, docIndex) => {
            const reportIndex = $(iframe).data("report-index");
            const fileIndex = nextFileIndex.get(reportIndex) ?? 0;
            nextFileIndex.set(reportIndex, fileIndex + 1);
            $(iframe).data("selected", docIndex == this._currentDocumentIndex);
            return { reportIndex, entries: sourceReports[reportIndex].ixIndex.docs[fileIndex] ?? [] };
        });

        this.itemContinuationMap = {};
        this.continuationOfMap = {};
        for (const [reportIndex, sr] of sourceReports.entries()) {
            for (const [headId, chain] of Object.entries(sr.ixIndex.continuations)) {
                const head = viewerUniqueId(reportIndex, headId);
                const continuations = chain.map(id => viewerUniqueId(reportIndex, id));
                this.itemContinuationMap[head] = continuations;
                for (const c of continuations) {
                    this.continuationOfMap[c] = head;
                }
            }
        }

        for (const [docIndex, { reportIndex, entries }] of docs.entries()) {
            const locators = new Map();
            this._locators.push(locators);
            for (const [kind, id, inHidden, extra] of entries) {
                const locator = { docIndex, elementId: id, kind, inHidden: inHidden === 1 };
                locators.set(id, locator);
                if (kind === "l") {
                    const vuid = viewerUniqueId(reportIndex, extra);
                    locator.vuid = vuid;
                    this.docOrderItemIndex.addItem(vuid, docIndex);
                    const ixn = this._ixNodeMap[vuid];
                    if (ixn) {
                        ixn.locator = locator;
                        ixn.docIndex = docIndex;
                    }
                    else {
                        this._ixNodeMap[vuid] = new LazyIXNode(vuid, locator, docIndex, this);
                    }
                    continue;
                }
                const vuid = viewerUniqueId(reportIndex, id);
                locator.vuid = vuid;
                if (kind === "c") {
                    if (this.continuationOfMap[vuid] !== undefined) {
                        this._getOrCreateLazyIXNode(vuid, locator, docIndex, locator.inHidden);
                    }
                    continue;
                }
                // As in Viewer._preProcessiXBRL, a hidden fact is in document
                // order where its -ix-hidden reference shows it.
                const shownByReference = vuid in this._ixNodeMap;
                const ixn = this._getOrCreateLazyIXNode(vuid, locator, docIndex, locator.inHidden);
                this.itemContinuationMap[vuid] ??= [];
                if (!shownByReference) {
                    this.docOrderItemIndex.addItem(vuid, docIndex);
                }
                if (kind === "f" && extra !== undefined) {
                    ixn.scale = extra;
                }
                else if (kind === "n" && extra === 1) {
                    ixn.escaped = true;
                }
                else if (kind === "t") {
                    ixn.footnote = true;
                }
            }
        }
        for (const [itemId, continuations] of Object.entries(this.itemContinuationMap)) {
            if (this._ixNodeMap[itemId] !== undefined) {
                this._ixNodeMap[itemId].continuations = continuations.map(id => this._ixNodeMap[id]).filter(n => n !== undefined);
            }
        }
    }

    _getOrCreateLazyIXNode(vuid, locator, docIndex, isHidden) {
        let ixn = this._ixNodeMap[vuid];
        if (!ixn) {
            ixn = new LazyIXNode(vuid, locator, docIndex, this);
            this._ixNodeMap[vuid] = ixn;
        }
        ixn.isHidden = isHidden;
        return ixn;
    }

    _locatorForElement(docIndex, element) {
        return element.id ? this._locators[docIndex].get(element.id) : undefined;
    }

    // Returns wrapper nodes for the locator, wrapping it and any related
    // elements first if required.  Returns undefined if the element has not
    // been loaded yet.
    wrapLocator(locator) {
        if (locator.nodes === undefined) {
            const doc = this._iframes.get(locator.docIndex).contentDocument;
            const element = doc.getElementById(locator.elementId);
            if (element === null) {
                return undefined;
            }
            this._wrapTree(locator.docIndex, element);
        }
        return locator.nodes;
    }

    // Wrap all indexed elements in the subtree of the outermost indexed
    // ancestor of element, children first, as nested elements share wrappers.
    _wrapTree(docIndex, element) {
        let top = element;
        for (let a = element.parentElement; a !== null; a = a.parentElement) {
            if (this._locatorForElement(docIndex, a) !== undefined) {
                top = a;
            }
        }
        this._wrapSubtree(docIndex, top);
    }

    _wrapSubtree(docIndex, root) {
        const preOrder = [];
        if (this._locatorForElement(docIndex, root) !== undefined) {
            preOrder.push(root);
        }
        for (const e of root.getElementsByTagName("*")) {
            if (e.id && this._locators[docIndex].has(e.id)) {
                preOrder.push(e);
            }
        }
        const stack = [];
        const postOrder = [];
        for (const e of preOrder) {
            while (stack.length > 0 && !stack.at(-1).contains(e)) {
                postOrder.push(stack.pop());
            }
            stack.push(e);
        }
        while (stack.length > 0) {
            postOrder.push(stack.pop());
        }
        for (const e of postOrder) {
            const locator = this._locatorForElement(docIndex, e);
            if (locator.nodes === undefined) {
                this._wrapElement(locator, e);
            }
        }
    }

    _wrapElement(locator, element) {
        const nodes = this._findOrCreateWrapperNode(element, locator.inHidden);
        if (locator.kind === "l") {
            nodes.addClass("ixbrl-element").data('ivids', [locator.vuid]);
        }
        else if (locator.kind === "c") {
            const head = this.continuationOfMap[locator.vuid];
            if (head !== undefined) {
                this._addIdToNodes(nodes, head);
                nodes.addClass("ixbrl-continuation");
            }
        }
        else {
            this._addIdToNodes(nodes, locator.vuid);
            nodes.addClass(KIND_CLASSES[locator.kind]);
        }
        locator.nodes = nodes;
        const wrappers = nodes.filter(".ixbrl-element").get();
        this._bindWrapperHandlers(wrappers);
        this._newWrappers.push(...wrappers);
        for (const e of nodes.filter(".ixbrl-contains-absolute").get()) {
            this._checkContainsAbsolute(e);
        }
    }

    _checkContainsAbsolute(e) {
        if (getComputedStyle(e).getPropertyValue("display") !== 'inline') {
            // The first read can report a zero height, so read twice.
            e.getBoundingClientRect().height;
            if (e.getBoundingClientRect().height == 0) {
                e.classList.add("ixbrl-no-highlight");
            }
        }
    }

    // Wrap the indexed elements that an event at target could be over.
    // Returns the new wrappers.
    _prepareTarget(docIndex, target) {
        this._newWrappers = [];
        const body = target.ownerDocument.body;
        for (let a = target; a !== null && a !== body; a = a.parentElement) {
            const locator = this._locatorForElement(docIndex, a);
            if (locator !== undefined && locator.nodes === undefined) {
                this._wrapTree(docIndex, a);
            }
            if ((a.nodeName === 'TD' || a.nodeName === 'TH') && !this._cellsChecked.has(a)) {
                this._cellsChecked.add(a);
                const descendants = a.getElementsByTagName("*");
                if (descendants.length <= CELL_SCAN_LIMIT) {
                    for (const e of descendants) {
                        const l = this._locatorForElement(docIndex, e);
                        if (l !== undefined && l.nodes === undefined) {
                            this._wrapTree(docIndex, e);
                        }
                    }
                }
            }
            if (a.nodeName === 'TABLE' && !this._tablesChecked.has(a)) {
                this._tablesChecked.add(a);
                this._addTableHandle(docIndex, a);
            }
        }
        const created = this._newWrappers;
        this._newWrappers = [];
        return created;
    }

    _bindWrapperHandlers(elements) {
        const viewer = this;
        const unbound = elements.filter(e => !this._bound.has(e));
        for (const e of unbound) {
            this._bound.add(e);
        }
        $(unbound)
            .on("click", function (e) {
                e.stopPropagation();
                viewer.selectElementByClick($(this));
            })
            .on("mouseenter", function (e) { viewer._mouseEnter($(this)) })
            .on("mouseleave", function (e) { viewer._mouseLeave($(this)) });
    }

    // Matches the condition used by TableExport.addHandles, without requiring
    // the table's facts to be wrapped.
    _addTableHandle(docIndex, table) {
        let rowsWithFacts = 0;
        for (const row of table.getElementsByTagName("tr")) {
            for (const e of row.getElementsByTagName("*")) {
                const l = this._locatorForElement(docIndex, e);
                if (l !== undefined && !l.inHidden) {
                    rowsWithFacts++;
                    break;
                }
            }
            if (rowsWithFacts > 1) {
                TableExport.addHandle($(table), this._reportSet, () => this._wrapAll(docIndex, table));
                return;
            }
        }
    }

    _wrapAll(docIndex, root) {
        this._wrapSubtree(docIndex, root);
        this._newWrappers = [];
    }

    _bindHandlers() {
        const viewer = this;
        for (const [docIndex, iframe] of this._iframes.toArray().entries()) {
            const doc = iframe.contentDocument;
            const reportIndex = $(iframe).data("report-index");
            // Capture phase, so that wrappers exist before the event reaches them.
            doc.addEventListener("pointerdown", (e) => this._prepareTarget(docIndex, e.target), true);
            doc.addEventListener("mouseover", (e) => {
                const created = this._prepareTarget(docIndex, e.target);
                // Wrappers inserted during this event miss its mouseenter.
                const entered = created.filter(w => w.contains(e.target));
                if (entered.length > 0) {
                    this._mouseEnter($(entered.at(-1)));
                }
            }, true);
            doc.addEventListener("click", (e) => {
                const link = e.target.closest?.("a[href]");
                if (link) {
                    this._handleLinkClick(link, reportIndex, e);
                }
            }, true);
            $(doc.body).on("click", () => viewer.selectElement(null));
        }
    }

    // Equivalent to the handling set up by Viewer._updateLink.
    _handleLinkClick(n, reportIndex, e) {
        const [file, fragment] = n.getAttribute("href").split('#', 2);
        const docIndex = this._linkDocIndex(file, reportIndex);
        if (docIndex != -1) {
            e.preventDefault();
            this._showDocumentAndElement(docIndex, fragment);
        }
        else if (file) {
            n.setAttribute("target", "_blank");
        }
    }

    showItemById(vuid) {
        this._whenLoaded(vuid, () => super.showItemById(vuid));
    }

    highlightItem(vuid) {
        this._whenLoaded(vuid, () => super.highlightItem(vuid));
    }

    // Run action now if the item's element has been loaded, or once it has
    // been, unless another item has been shown or highlighted in the meantime.
    _whenLoaded(vuid, action) {
        const locator = this._ixNodeMap[vuid]?.locator;
        const doc = locator === undefined ? undefined : this._iframes.get(locator.docIndex).contentDocument;
        if (doc === undefined || doc.readyState !== 'loading' || doc.getElementById(locator.elementId) !== null) {
            if (this._pending?.vuid !== vuid) {
                this._pending = undefined;
            }
            action();
            return;
        }
        if (this._pending?.vuid !== vuid) {
            this._pending = { vuid, actions: [] };
            const pending = this._pending;
            const retry = () => {
                if (this._pending !== pending) {
                    return;
                }
                if (doc.readyState === 'loading' && doc.getElementById(locator.elementId) === null) {
                    setTimeout(retry, 100);
                    return;
                }
                this._pending = undefined;
                for (const a of pending.actions) {
                    a();
                }
            };
            setTimeout(retry, 100);
        }
        this._pending.actions.push(action);
    }

    factsInSameTable(fact) {
        const e = this.elementsForItemId(fact.vuid);
        const table = e.closest("table").get(0);
        if (table !== undefined) {
            this._wrapAll(this._ixNodeMap[fact.vuid].docIndex, table);
        }
        return super.factsInSameTable(fact);
    }

    * postProcess() {
        // Wrappers are checked for absolutely positioned content as they are created.
    }

    postLoadAsync() {
        super.postLoadAsync();
        if (this._iv.isOffscreenRenderingSkipped()) {
            this._offscreen = this._iframes.get().map(iframe => this._skipOffscreenRendering(iframe));
        }
    }

    // Skipping relies on measured sizes, so it starts once everything that
    // affects layout has loaded, and restarts when the width changes.
    _skipOffscreenRendering(iframe) {
        const doc = iframe.contentDocument;
        const win = iframe.contentWindow;
        const offscreen = new OffscreenRendering(doc);
        let restartTimer;
        offscreen.restart = () => {
            offscreen.reset();
            clearTimeout(restartTimer);
            restartTimer = setTimeout(() => runGenerator(offscreen.start()), OFFSCREEN_RESTART_DELAY);
        };
        const start = () => {
            let width = win.innerWidth;
            win.addEventListener("resize", () => {
                if (win.innerWidth !== width) {
                    width = win.innerWidth;
                    offscreen.restart();
                }
            });
            // Containment would stop skipped blocks breaking across pages.
            win.addEventListener("beforeprint", () => offscreen.reset());
            win.addEventListener("afterprint", () => offscreen.restart());
            runGenerator(offscreen.start());
        };
        // Stylesheets moved into a reparented document load after it has.
        const loaded = () => doc.readyState === "complete"
            && [...doc.querySelectorAll('link[rel~="stylesheet"]')].every(link => link.sheet !== null)
            && [...doc.images].every(img => img.complete || img.loading === "lazy");
        const whenLoaded = () => {
            if (loaded()) {
                doc.fonts.ready.then(start);
            }
            else {
                setTimeout(whenLoaded, OFFSCREEN_LOAD_POLL_INTERVAL);
            }
        };
        whenLoaded();
        return offscreen;
    }

    zoom(pct) {
        this._offscreen?.forEach(o => o.reset());
        super.zoom(pct);
        this._offscreen?.forEach(o => o.restart());
    }
}
