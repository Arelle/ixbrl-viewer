import $ from "jquery";
import { ReportSet } from "./reportset.js";
import { Viewer } from "./viewer.js";
import { LazyViewer } from "./lazyViewer.js";
import { viewerUniqueId } from "./util.js";

const DOCUMENT = `
<ix:header><ix:hidden>
  <ix:nonNumeric id="h1" name="eg:Hidden1">hidden one</ix:nonNumeric>
  <ix:nonNumeric id="h2" name="eg:Hidden2">hidden two</ix:nonNumeric>
</ix:hidden></ix:header>
<p>Text <ix:nonFraction id="f1" scale="6">1,000</ix:nonFraction> more</p>
<table>
  <tr><td><ix:nonFraction id="f2">2</ix:nonFraction></td><td>Label <ix:nonFraction id="f3">3</ix:nonFraction></td></tr>
  <tr><td><ix:nonFraction id="f4"><ix:nonFraction id="f5">5</ix:nonFraction></ix:nonFraction></td></tr>
</table>
<div><ix:nonNumeric id="n1" continuedAt="c1" escape="true"><p>Block start</p></ix:nonNumeric></div>
<p><span style="-sec-ix-hidden: h1" id="link1">Hidden reference</span></p>
<ix:continuation id="c1"><p>Block end</p></ix:continuation>
<p><ix:nonFraction id="nil1"></ix:nonFraction></p>
<p><a href="other.htm">Other</a></p>
`;

// As generated by IXBRLViewerBuilder.buildDocumentIndex for DOCUMENT
const IX_INDEX = {
    docs: [[
        ["n", "h1", 1],
        ["n", "h2", 1],
        ["f", "f1", 0, 6],
        ["f", "f2", 0],
        ["f", "f3", 0],
        ["f", "f5", 0],
        ["f", "f4", 0],
        ["n", "n1", 0, 1],
        ["l", "link1", 0, "h1"],
        ["c", "c1", 0],
        ["f", "nil1", 0],
    ]],
    continuations: { n1: ["c1"] },
};

const FACT_IDS = ["h1", "h2", "f1", "f2", "f3", "f4", "f5", "n1", "nil1"];

function reportData(ixIndex = IX_INDEX, factIds = FACT_IDS) {
    const facts = Object.fromEntries(factIds.map(id => [id, { v: id, a: { c: "eg:Concept", p: "2017-01-01" } }]));
    return {
        sourceReports: [{
            docSetFiles: ["report.htm"],
            ixIndex: ixIndex,
            targetReports: [{
                concepts: { "eg:Concept": { labels: { std: { en: "A" } } } },
                facts,
                languages: {},
                roles: {},
                roleDefs: {},
                rels: {},
            }],
        }],
        prefixes: { eg: "http://www.example.com" },
    };
}

function makeIframe(body = DOCUMENT) {
    const iframe = document.createElement("iframe");
    document.body.appendChild(iframe);
    iframe.contentDocument.body.innerHTML = body;
    $(iframe).data("report-index", 0);
    return iframe;
}

const iv = { options: {}, isReviewModeEnabled: () => false, callPluginMethod: () => {} };

function makeFullViewer(body, ixIndex, factIds) {
    const iframe = makeIframe(body);
    const reportSet = new ReportSet(reportData(ixIndex, factIds));
    const viewer = new Viewer(iv, $(iframe), reportSet);
    viewer._buildContinuationMaps();
    viewer._preProcessiXBRL(iframe.contentDocument.body, 0, 0, false);
    viewer._setContinuationMaps();
    reportSet.setIXNodeMap(viewer._ixNodeMap);
    return { viewer, doc: iframe.contentDocument };
}

function makeLazyViewer(body, ixIndex, factIds) {
    const iframe = makeIframe(body);
    const reportSet = new ReportSet(reportData(ixIndex, factIds));
    const viewer = new LazyViewer(iv, $(iframe), reportSet);
    viewer._buildFromIndex();
    reportSet.setIXNodeMap(viewer._ixNodeMap);
    viewer._bindHandlers();
    return { viewer, doc: iframe.contentDocument };
}

function nodeSummary(viewer) {
    const nodes = Object.values(viewer._ixNodeMap).sort((a, b) => a.docOrderindex - b.docOrderindex);
    return nodes.map(n => ({
        id: n.id,
        docIndex: n.docIndex,
        isHidden: n.isHidden,
        scale: n.scale,
        escaped: n.escaped,
        footnote: n.footnote,
        continuations: n.continuationIds(),
    }));
}

function wrapperIds(doc) {
    return [...doc.querySelectorAll(".ixbrl-element")].map(e => $(e).data("ivids"));
}

describe("LazyViewer", () => {
    afterEach(() => {
        document.body.innerHTML = "";
    });

    test("builds the same nodes, order and continuation maps as a document walk", () => {
        const full = makeFullViewer().viewer;
        const lazy = makeLazyViewer().viewer;

        expect(nodeSummary(lazy)).toEqual(nodeSummary(full));
        expect(lazy.docOrderItemIndex._index).toEqual(full.docOrderItemIndex._index);
        expect(lazy.continuationOfMap).toEqual(full.continuationOfMap);
        expect(lazy.itemContinuationMap).toEqual(full.itemContinuationMap);
    });

    test.each([["full", makeFullViewer], ["lazy", makeLazyViewer]])("%s viewer marks a hidden fact linked to from earlier in the document as hidden", (_, makeViewer) => {
        const body = `
<p><span style="-sec-ix-hidden: h1" id="link1">Hidden reference</span></p>
<ix:header><ix:hidden>
  <ix:nonNumeric id="h1" name="eg:Hidden1">hidden one</ix:nonNumeric>
</ix:hidden></ix:header>
`;
        const ixIndex = { docs: [[["l", "link1", 0, "h1"], ["n", "h1", 1]]], continuations: {} };
        const { viewer } = makeViewer(body, ixIndex, ["h1"]);

        expect(viewer._ixNodeMap[viewerUniqueId(0, "h1")].isHidden).toBe(true);
    });

    test("does not modify the document until facts are needed", () => {
        const { doc } = makeLazyViewer();
        const pristine = makeIframe().contentDocument;

        expect(doc.body.innerHTML).toEqual(pristine.body.innerHTML);
    });

    test("wrapping the whole document produces the same document as a document walk", () => {
        const full = makeFullViewer();
        const lazy = makeLazyViewer();
        // Link targets are set when a link is clicked.
        full.doc.querySelector("a").removeAttribute("target");

        lazy.viewer._wrapAll(0, lazy.doc.body);

        expect(lazy.doc.body.innerHTML).toEqual(full.doc.body.innerHTML);
        expect(wrapperIds(lazy.doc)).toEqual(wrapperIds(full.doc));
    });

    test("wrapping every fact gives each the same wrappers as a document walk", () => {
        const full = makeFullViewer();
        const lazy = makeLazyViewer();

        for (const vuid of Object.keys(lazy.viewer._ixNodeMap)) {
            lazy.viewer.elementsForItemId(vuid);
        }

        for (const vuid of Object.keys(full.viewer._ixNodeMap)) {
            const outer = (viewer) => viewer.elementsForItemId(vuid).get().map(e => e.outerHTML);
            expect(outer(lazy.viewer)).toEqual(outer(full.viewer));
        }
    });

    test("opens links to other files in a new tab when clicked", () => {
        const { doc } = makeLazyViewer();
        const link = doc.querySelector("a");
        link.addEventListener("click", e => e.preventDefault());

        link.dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true }));

        expect(link.getAttribute("target")).toBe("_blank");
    });

    test.each([
        ["full", makeFullViewer, (viewer, link) => viewer._updateLink(link, 0)],
        ["lazy", makeLazyViewer, () => {}],
    ])("%s viewer shows links to files in the document set in the viewer", (_, makeViewer, prepareLink) => {
        const { viewer, doc } = makeViewer();
        const show = jest.spyOn(viewer, "_showDocumentAndElement").mockImplementation(() => {});
        const link = doc.createElement("a");
        link.setAttribute("href", "report.htm#f1");
        doc.body.appendChild(link);
        prepareLink(viewer, link);

        const click = new MouseEvent("click", { bubbles: true, cancelable: true });
        link.dispatchEvent(click);

        expect(show).toHaveBeenCalledWith(0, "f1");
        expect(click.defaultPrevented).toBe(true);
        expect(link.hasAttribute("target")).toBe(false);
    });

    test.each([
        ["full", makeFullViewer, (viewer, link) => viewer._updateLink(link, 0)],
        ["lazy", makeLazyViewer, () => {}],
    ])("%s viewer shows links to files in the linking report's document set", (_, makeViewer, prepareLink) => {
        const { viewer, doc } = makeViewer();
        jest.spyOn(viewer._reportSet, "reportFiles").mockReturnValue([
            { index: 1, file: "report.htm" },
            { index: 0, file: "report.htm" },
        ]);
        const show = jest.spyOn(viewer, "_showDocumentAndElement").mockImplementation(() => {});
        const link = doc.createElement("a");
        link.setAttribute("href", "report.htm#f1");
        doc.body.appendChild(link);
        prepareLink(viewer, link);

        link.dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true }));

        expect(show).toHaveBeenCalledWith(1, "f1");
    });

    test("wrapping one nested fact wraps its enclosing facts in document walk order", () => {
        const full = makeFullViewer();
        const lazy = makeLazyViewer();

        lazy.viewer.elementsForItemId(viewerUniqueId(0, "f5"));

        const cell = (doc) => doc.getElementById("f4").closest("td").outerHTML;
        expect(cell(lazy.doc)).toEqual(cell(full.doc));
    });

    test("selects a fact clicked before it has been wrapped", () => {
        const { viewer, doc } = makeLazyViewer();
        const selected = jest.fn();
        viewer.onSelect.add(selected);

        const target = doc.getElementById("f3");
        target.dispatchEvent(new MouseEvent("pointerdown", { bubbles: true }));
        target.dispatchEvent(new MouseEvent("click", { bubbles: true }));

        expect(selected).toHaveBeenCalledWith(viewerUniqueId(0, "f3"), [viewerUniqueId(0, "f3")], true);
    });

    test("selects a fact that uses its table cell as a wrapper when the cell is clicked", () => {
        const { viewer, doc } = makeLazyViewer();
        const selected = jest.fn();
        viewer.onSelect.add(selected);

        const cell = doc.getElementById("f2").closest("td");
        cell.dispatchEvent(new MouseEvent("pointerdown", { bubbles: true }));
        cell.dispatchEvent(new MouseEvent("click", { bubbles: true }));

        expect(selected).toHaveBeenCalledWith(viewerUniqueId(0, "f2"), [viewerUniqueId(0, "f2")], true);
    });

    test("clears the selection when untagged content is clicked", () => {
        const { viewer, doc } = makeLazyViewer();
        const selected = jest.fn();
        viewer.onSelect.add(selected);

        const target = doc.querySelector("p");
        target.dispatchEvent(new MouseEvent("pointerdown", { bubbles: true }));
        target.dispatchEvent(new MouseEvent("click", { bubbles: true }));

        expect(selected).toHaveBeenCalledWith(null);
    });

    test("locates a hidden fact by the element that references it", () => {
        const { viewer, doc } = makeLazyViewer();

        const nodes = viewer.elementsForItemId(viewerUniqueId(0, "h1"));

        expect(nodes.get(0)).toBe(doc.getElementById("link1").parentNode);
        expect(nodes.data("ivids")).toEqual([viewerUniqueId(0, "h1")]);
    });

    test("returns no wrapper for a fact that has not been loaded yet", () => {
        const { viewer, doc } = makeLazyViewer();
        const f1 = doc.getElementById("f1");
        const parent = f1.parentNode;
        f1.remove();

        expect(viewer.elementsForItemId(viewerUniqueId(0, "f1")).length).toBe(0);

        parent.appendChild(f1);
        expect(viewer.elementsForItemId(viewerUniqueId(0, "f1")).length).toBe(1);
    });

    describe("selecting a fact that has not been loaded yet", () => {
        let viewer, doc, f1, parent, showElement, state;

        beforeEach(() => {
            jest.useFakeTimers();
            ({ viewer, doc } = makeLazyViewer());
            state = "loading";
            Object.defineProperty(doc, "readyState", { get: () => state, configurable: true });
            f1 = doc.getElementById("f1");
            parent = f1.parentNode;
            f1.remove();
            showElement = jest.spyOn(viewer, "showElement").mockImplementation(() => {});
        });

        afterEach(() => {
            jest.useRealTimers();
        });

        test("shows and highlights it once it loads", () => {
            const vuid = viewerUniqueId(0, "f1");
            viewer.showItemById(vuid);
            viewer.highlightItem(vuid);
            expect(showElement).not.toHaveBeenCalled();

            parent.appendChild(f1);
            jest.advanceTimersByTime(100);

            expect(showElement).toHaveBeenCalledTimes(1);
            expect(f1.parentNode.classList.contains("ixbrl-selected")).toBe(true);
        });

        test("abandons it if another fact is selected first", () => {
            viewer.showItemById(viewerUniqueId(0, "f1"));
            viewer.showItemById(viewerUniqueId(0, "f2"));
            expect(showElement).toHaveBeenCalledTimes(1);

            parent.appendChild(f1);
            jest.advanceTimersByTime(100);

            expect(showElement).toHaveBeenCalledTimes(1);
        });

        test("stops waiting once the document has loaded", () => {
            viewer.showItemById(viewerUniqueId(0, "f1"));
            state = "interactive";
            jest.advanceTimersByTime(100);

            expect(showElement).not.toHaveBeenCalled();
        });
    });

    test("is only used when every source report has a document index", () => {
        expect(LazyViewer.documentIndexAvailable(new ReportSet(reportData()))).toBe(true);
        const data = reportData();
        delete data.sourceReports[0].ixIndex;
        expect(LazyViewer.documentIndexAvailable(new ReportSet(data))).toBe(false);
    });
});
